UIImage *FXLogoImage(void)
{
    static UIImage *image = nil;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        NSData *data = [[NSData alloc] initWithBase64EncodedString:kFXLogoBase64 options:0];
        if (data.length > 0)
        {
            image = [UIImage imageWithData:data];
        }
    });
    return image;
}
